"""Exact transparent bounds: never remove any nonzero-alpha texel."""
from pathlib import Path
import hashlib
import struct
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
def main():
    raw=(ROOT/'output/lunaria/atlas.argb').read_bytes()
    atlas=Image.frombytes('RGBA',(640,480),raw,'raw','BGRA')
    h=2166136261
    for (word,) in struct.iter_unpack('<I',raw): h=((h^word)*16777619)&0xffffffff
    def bounds(x,y,w,h):
        box=atlas.crop((x,y,x+w,y+h)).getchannel('A').getbbox()
        if box is None:return (0,0,0,0)
        l,t,r,b=box;l=l//4*4;r=min(w,(r+3)//4*4)
        return l,t,r-l,b-t
    groups={
        'ln_bounds32':[bounds(448+i%6*32,i//6*32,32,32) for i in range(66)],
        'ln_bounds_boss':[bounds(i%4*112,i//4*112,112,112) for i in range(16)],
        'ln_bounds_glyph':[bounds(448+i%16*12,352+i//16*24,12,24) for i in range(64)],
        'ln_bounds_title':[bounds(0,448,256,32),bounds(256,448,192,32)]}
    text='/* Generated by scripts/prepare_lunaria_trim.py; zero-alpha pixels only. */\n'
    text+='#ifndef LUNARIA_TRIM_H\n#define LUNARIA_TRIM_H\n#include "lunaria_asset_ids.h"\n'
    text+=f'typedef char ln_trim_matches_atlas[(LN_ATLAS_HASH == UINT32_C(0x{h:08x})) ? 1 : -1];\n'
    for name,rows in groups.items():
        text+=f'static const uint8_t {name}[{len(rows)}][4] = {{\n'
        text+=''.join('  {'+','.join(map(str,r))+'},\n' for r in rows)+'};\n'
    text+='#endif\n'
    (ROOT/'software/lunaria/lunaria_trim.h').write_text(text,encoding='utf8')
    print('PASS generated exact transparent bounds for 148 atlas regions; atlas SHA256 '+hashlib.sha256(raw).hexdigest())
if __name__=='__main__':main()
