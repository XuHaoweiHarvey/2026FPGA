"""Prepare the supplied island image and compact fullscreen firmware background."""
import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageEnhance, ImageOps

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "assets/team_background"
HEADER = ROOT / "software/interactive_demo/game_background_asset.h"


def generate():
    with Image.open(ART / "island.png") as source:
        image = source.convert("RGB")
    if image.size != (160, 90):
        raise ValueError("Expected 160x90 source PNG")
    pixels = list(image.get_flattened_data() if hasattr(image, "get_flattened_data") else image.getdata())
    palette = sorted(set(pixels))
    if len(palette) > 128:
        raise ValueError("Background must use at most 128 colors")
    lookup = {p: i for i, p in enumerate(palette)}
    indices = [lookup[p] for p in pixels]
    lines = ["/* Generated by tools/prepare_game_background.py. */",
             "#ifndef GAME_BACKGROUND_ASSET_H", "#define GAME_BACKGROUND_ASSET_H", "#include <stdint.h>",
             "static const uint32_t game_background_palette[] = {"]
    lines += ["    " + ",".join(f"UINT32_C(0x{r:02x}{g:02x}{b:02x})" for r, g, b in palette) + "\n};",
              "static const uint8_t game_background_pixels[] = {"]
    lines += ["    " + ",".join(str(v) for v in indices[i:i+32]) + "," for i in range(0, len(indices), 32)]
    lines += ["};", "static inline uint32_t game_background_pixel(uint32_t x, uint32_t y) {",
              "    return game_background_palette[game_background_pixels[(y / 12u) * 160u + x / 12u]];",
              "}", "#endif", ""]
    return "\n".join(lines), len(indices) + 4 * len(palette)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.source:
        if args.check:
            parser.error("--check cannot import")
        ART.mkdir(parents=True, exist_ok=True)
        with Image.open(args.source) as source:
            image = ImageOps.fit(source.convert("RGB"), (160, 90), Image.Resampling.NEAREST)
        # Dim the scene so green/red projectiles remain easy to identify.
        image = ImageEnhance.Brightness(image).enhance(0.55)
        image = image.quantize(colors=128, dither=Image.Dither.NONE).convert("RGB")
        image.save(ART / "island.png")
        (ART / "source.json").write_text(json.dumps({"file": args.source.name,
            "sha256": hashlib.sha256(args.source.read_bytes()).hexdigest()}, indent=2) + "\n", encoding="utf8")
    header, size = generate()
    if args.check:
        if HEADER.read_text(encoding="utf8") != header:
            raise SystemExit("Background C header differs from PNG")
        print("PASS compact background matches source PNG")
    else:
        HEADER.write_text(header, encoding="utf8")
        with Image.open(ART / "island.png") as image:
            image.resize((960, 540), Image.Resampling.NEAREST).save(ART / "preview.png")
        print(f"Prepared fullscreen background: {size} embedded bytes, expands to 1920x1080")


if __name__ == "__main__":
    main()
